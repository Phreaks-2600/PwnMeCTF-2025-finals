@dataclass
class Block:
    """
    A block is simply 16 bytes
    """
    values: bytes # length always 16

    def __xor__(self, other: "Block"):
        # Apply xor byte per byte
        return Block(
            bytes(a ^ b for a, b in zip(self.values, other.values))
        )

    def shiftrows(self):
        """
        AES ShiftRows, in place
        """
        s = list(self.values)
        s[0], s[4], s[8],  s[12] = s[0],  s[4], s[8], s[12]
        s[1], s[5], s[9],  s[13] = s[5],  s[9], s[13], s[1]
        s[2], s[6], s[10], s[14] = s[10], s[14], s[2], s[6]
        s[3], s[7], s[11], s[15] = s[15], s[3], s[7], s[11]
        self.values = bytes(s)

    def subbytes(self):
        """
        AES SubBytes, in place
        """
        self.values = bytes(SBox[x] for x in self.values)

    def mixcolumns(self):
        """
        AES MixColumn, in place
        """
        s = list(self.values)
        out = []
        for x in range(0, 16, 4):
            col = s[x:x+4]
            out.extend([
                G2[col[0]] ^ G3[col[1]] ^ col[2] ^ col[3],
                col[0] ^ G2[col[1]] ^ G3[col[2]] ^ col[3],
                col[0] ^ col[1] ^ G2[col[2]] ^ G3[col[3]],
                G3[col[0]] ^ col[1] ^ col[2] ^ G2[col[3]]
            ])
        self.values = bytes(out)

    def aes_round(self):
        """
        One full keyless AES round
        """
        self.subbytes()
        self.shiftrows()
        self.mixcolumns()
